"""Габаритный коридор: заметаемый объём поезда вдоль предсказанного пути.

Всё, что строилось до сих пор (§15–§21), отвечало на вопрос «какой формы тоннель».
ТЗ спрашивает другое: «есть ли препятствие и на каком расстоянии». Между этими
двумя вещами нужен мост, и это он: жёсткий габарит подвижного состава,
протащенный по найденному пути. Что попало внутрь — то мешает проехать.

## Почему в координатах пути это просто коробка

Соблазнительно строить цепочку жёстких колец, соединённых связями, и гнуть её
вдоль тоннеля. Но в координатах пути `(d, u, v)`, которые мы и так считаем,
заметаемый объём — это в точности ПРЯМОУГОЛЬНАЯ КОРОБКА постоянного сечения:

    |u| <= HALF_WIDTH,   V_BOT <= v <= V_TOP

Потому что `u` отсчитывается по нормали к пути, а `v` — от плоскости головок
рельсов. Кривизна, уклон и рыскание уже поглощены самим переходом в эти
координаты. Кольца и связи между ними — это дискретизация того, что здесь
делается аналитически, и она не нужна.

Важное следствие: габарит НЕ подстраивается под тоннель. Он жёсткий по
определению — если бы он сжимался в узком месте, узкое место перестало бы быть
препятствием, а оно им и является.

## Откуда взяты размеры — из данных, а не из справочника

Карта занятости `(u, v)` по 198 кадрам пяти чистых прогонов (срезы 5–40 м)
показывает свободное сечение прямо:

  v < 0.5 м      — путь: шпалы, головки рельсов, скрепления. Занято ВСЕГДА.
  v = 0.6…3.6 м  — свободно при |u| <~ 1.1 м; занятость ниже 2% кадров.
  v > 3.9 м      — свод, занято везде.
  u = +1.4…1.6   — устойчивое скопление на v = 0.4…1.6 (контактный рельс).

Отсюда и размеры. Нижняя граница 0.6 м, а не 0.1 м над головкой рельса, как
кажется из габаритного чертежа: ниже лидар видит сам путь, и всё это —
известная инфраструктура, а не препятствие. Верхняя 3.6 м — ниже свода.

Полуширина 1.1 м уже полуширины вагона (около 1.35 м): между ними лежит
контактный рельс и кабельные лотки, которые в габарит приближения строений
входят, а в заметаемый объём кузова — нет. Расширять коробку до 1.35 м можно,
но замер показал, что это резко поднимает ложные срабатывания.

## Что дальше предела наблюдения

Глубже, чем стены реально видно (`tracked_depth`, сейчас медиана 78 м), путь —
уже не измерение, а продолжение модели. Экстраполированная парабола там
расходится: замер показал, что полуширина стены на 60–80 м уходит в
ОТРИЦАТЕЛЬНЫЕ значения на трёх прогонах из пяти.

Поэтому коридор за пределом наблюдения не продолжается одной кривой, а
РАСШИРЯЕТСЯ в конус: поезд не может повернуть круче `MIN_RADIUS`, значит на
глубине `D` за пределом `L` он отклонится не больше чем на `(D−L)²/(2·R)`.
Внутри конуса препятствие «возможно», а не «обнаружено», и утверждать про него
надо соответственно.
"""

import numpy as np

from .tunnel_frame import MIN_RADIUS, to_track_coords, tracked_depth

# ГАБАРИТ ВАГОНА — паспортные размеры 81-717/714 (основной тип московского
# метро): кузов 2670 мм в ширину, 3650 мм в высоту от уровня головок рельсов,
# 19206 мм в длину. Отсюда полуширина 1.335 м и верх 3.65 м.
#
# Данные это подтверждают независимо. Карта занятости (u, v) по 198 кадрам пяти
# чистых прогонов: свободная полуширина 1.1–1.4 м, свод занят с 3.9 м. То есть
# вагон проходит почти впритык — как и положено метро, где тоннель строится под
# габарит, а не с запасом.
HALF_WIDTH = 1.335    # м вбок от оси пути (кузов 2670 мм)
V_TOP = 3.65          # м над головкой рельса (высота кузова)

# Нижняя граница РАЗБОРА, а не габарита. Сам габарит начинается почти от головки
# рельса, но ниже 0.5 м лидар всегда видит путь: шпалы, скрепления, головки
# рельсов — занятость 100% на всех прогонах. Это известная инфраструктура, и
# отделять её от предмета на путях по одной только высоте нельзя.
#
# ЦЕНА ЭТОГО ЯВНАЯ: предмет НИЖЕ 0.5 м над головкой рельса детектор не увидит.
# Лежащий на путях груз, упавший человек — вне зоны разбора. Лечится не порогом,
# а сравнением профиля пути с эталонным (§10 показал, что для таких вещей нужен
# эталон формы и остаток, а не кластеризация).
V_BOT = 0.50

AXIS_SIGMA = 0.15     # м: 90-й перцентиль ошибки оси (§21) — запас коридора
# DBSCAN внутри габарита. eps 0.35 м — крупнее шага между соседними кольцами на
# 20-30 м, иначе один предмет рассыпется на кольца; min_samples 12 отсекает
# одиночные отражения. Перед кластеризацией облако прореживается по сетке 5 см:
# без этого ближняя зона даёт сотни тысяч точек и DBSCAN считается минутами, а
# добавляет только плотность там, где её и так с избытком.
DBSCAN_EPS = 0.35
DBSCAN_MIN_SAMPLES = 12
VOXEL = 0.05
MIN_CLUSTER_POINTS = 25   # вокселей в кластере
MIN_CLUSTER_EXTENT = 0.25 # м: наибольший габарит кластера — тоньше это шум, а не предмет
MIN_CLUSTER = 25      # точек в срезе: меньше — одиночные отражения, не объект
DEPTH_BIN = 1.0       # м: срез, в котором считается вторжение
NEAR_LIMIT = 2.0      # м: ближе этого — собственная конструкция поезда (§12)
# Дальше этого коридору верить нельзя: подгонка кончается на 42 м, а ось за 40 м
# уже заметно гуляет. Замер: при пределе 40 м ложные срабатывания на двухпутном
# прогоне 29% против 17% при 30 м, при том же габарите.
TRUST_DEPTH = 30.0


def corridor_halfwidth(d, reach=None):
    """Полуширина коридора на глубине d: сам габарит плюс неопределённость.

    До предела наблюдения это габарит плюс ошибка оси. Дальше добавляется
    геометрический конус: за пределом наблюдения путь не измерен, и поезд может
    уйти вбок на `(d−reach)²/(2·MIN_RADIUS)` — больше не даёт физика трассы.
    """
    d = np.asarray(d, dtype=float)
    out = np.full(d.shape, HALF_WIDTH + AXIS_SIGMA)
    if reach:
        beyond = np.maximum(d - float(reach), 0.0)
        out = out + beyond ** 2 / (2.0 * MIN_RADIUS)
    return out


def intrusions(points, res, half_width=HALF_WIDTH, strict=True, d_max=130.0,
               trust=TRUST_DEPTH):
    """Точки, попавшие в габарит, сгруппированные по срезам глубины.

    strict=True — коридор постоянной ширины (габарит плюс запас на ошибку оси);
        только до предела наблюдения, где путь измерен.
    strict=False — коридор расширяется конусом за пределом наблюдения; находки
        там означают «возможно», а не «обнаружено».

    Возвращает dict: mask (по точкам), depth (глубина ближайшего скопления),
    slices (список срезов с числом точек), reach.
    """
    x = points['x'].astype(float)
    y = points['y'].astype(float)
    z = points['z'].astype(float)
    d, u, v = to_track_coords(x, y, z, res["frame"])

    reach = [tracked_depth(res, s) for s in ("left", "right")]
    reach = [r for r in reach if r]
    reach = float(np.mean(reach)) if reach else None

    limit = trust if strict else d_max
    w = (np.full(d.shape, half_width) if strict
         else corridor_halfwidth(d, reach) - HALF_WIDTH + half_width)
    inside = ((np.abs(u) < w) & (v >= V_BOT) & (v <= V_TOP)
              & (d > NEAR_LIMIT) & (d < limit))

    # Одиночные точки — это отражения от пыли и краёв, а не объект. Объект
    # занимает срез: тот же довод, что в §12, где морфологическое объединение
    # понадобилось именно из-за дробления реального препятствия.
    slices, nearest = [], None
    if inside.any():
        di = d[inside]
        edges = np.arange(NEAR_LIMIT, limit + DEPTH_BIN, DEPTH_BIN)
        counts, _ = np.histogram(di, bins=edges)
        for k in np.flatnonzero(counts >= MIN_CLUSTER):
            slices.append({"depth": float((edges[k] + edges[k + 1]) / 2),
                           "n": int(counts[k])})
        if slices:
            nearest = slices[0]["depth"]
    return {"mask": inside, "depth": nearest, "slices": slices, "reach": reach}


class ObstacleWatch:
    """Подтверждение находки по нескольким кадрам подряд.

    Ключевой признак, ради которого всё и строилось: НЕПОДВИЖНОЕ препятствие
    приближается ровно на Δs за кадр, а Δs мы умеем мерить (§20) с точностью до
    сантиметра. Ложное срабатывание от дрожания оси этому правилу не подчиняется
    — оно возникает и пропадает на месте.

    Поэтому подтверждается не «точки в габарите есть», а «точки в габарите есть
    там, где их предсказало прошлое наблюдение с поправкой на пройденный путь».
    """

    def __init__(self, confirm=3, tol=1.5):
        self.confirm = confirm
        self.tol = tol
        self.reset()

    def reset(self):
        self.track = None      # (ожидаемая глубина, сколько кадров подтверждено)

    def update(self, depth, shift):
        """depth — глубина ближайшего скопления в габарите (или None).
        shift — измеренное Δs. Возвращает подтверждённую глубину либо None."""
        if depth is None:
            self.track = None
            return None
        if self.track is not None and shift is not None and np.isfinite(shift):
            expected = self.track[0] - shift
            if abs(depth - expected) < self.tol:
                self.track = (depth, self.track[1] + 1)
            else:
                self.track = (depth, 1)
        else:
            self.track = (depth, 1)
        return depth if self.track[1] >= self.confirm else None


def _voxel_downsample(pts, size=VOXEL):
    """Прореживание по сетке: один представитель на ячейку. Нужно до DBSCAN —
    иначе ближняя зона с сотнями тысяч точек считается минутами, а плотность
    там и так избыточна."""
    if len(pts) == 0:
        return pts, np.zeros(0, dtype=np.int64)
    keys = np.floor(pts / size).astype(np.int64)
    _, idx = np.unique(keys, axis=0, return_index=True)
    return pts[idx], idx


def cluster_obstacles(points, res, half_width=HALF_WIDTH, trust=TRUST_DEPTH,
                      eps=DBSCAN_EPS, min_samples=DBSCAN_MIN_SAMPLES):
    """DBSCAN по точкам ВНУТРИ габарита. Возвращает список кластеров.

    Кластеризация идёт в координатах пути (d, u, v): они почти изометричны
    декартовым, поэтому евклидово расстояние в них осмысленно, а форма коридора
    в них прямая — это и позволяет искать предмет, не выпрямляя облако.

    Отбор после кластеризации двойной: размер (число вокселей) и ПРОТЯЖЁННОСТЬ.
    Второе существеннее: скользящий вдоль стены шум даёт много точек, но он
    плоский, а предмет на путях имеет габарит во всех трёх измерениях.
    """
    from sklearn.cluster import DBSCAN

    x = points['x'].astype(float)
    y = points['y'].astype(float)
    z = points['z'].astype(float)
    d, u, v = to_track_coords(x, y, z, res["frame"])
    inside = ((np.abs(u) < half_width) & (v >= V_BOT) & (v <= V_TOP)
              & (d > NEAR_LIMIT) & (d < trust))
    if inside.sum() < min_samples:
        return [], inside

    pts = np.column_stack([d[inside], u[inside], v[inside]])
    small, keep = _voxel_downsample(pts)
    labels = DBSCAN(eps=eps, min_samples=min_samples).fit_predict(small)

    out = []
    for lab in np.unique(labels[labels >= 0]):
        m = labels == lab
        if m.sum() < MIN_CLUSTER_POINTS:
            continue
        c = small[m]
        size = c.max(axis=0) - c.min(axis=0)
        if size.max() < MIN_CLUSTER_EXTENT:
            continue
        out.append({"depth": float(c[:, 0].min()), "n": int(m.sum()),
                    "size": tuple(float(t) for t in size),
                    "u": float(np.median(c[:, 1])), "v": float(np.median(c[:, 2]))})
    out.sort(key=lambda c: c["depth"])
    return out, inside
