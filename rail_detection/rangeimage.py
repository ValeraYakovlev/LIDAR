"""Облако как range image: (азимут × кольцо), и признак «это сплошная поверхность».

Облако лидара приходит не мешком точек, а строго организованной сеткой — это
проверено на данных (knowledge.md §11), и здесь эта структура наконец
используется. Раскладка: `reshape(n/128, 128)` — ось 0 азимут, ось 1 кольцо.

Замер на записях показал ещё одну деталь: СОСЕДНИЕ КОЛОНКИ ПОПАРНО ДУБЛИРУЮТСЯ —
у 99% пар совпадают и дальность, и интенсивность (режим двух эхо, где второго
эха нет). Полезных азимутов поэтому вдвое меньше числа колонок: 1200 шагов по
0.1° в секторе ±50°. Дубликаты убираются сразу, иначе «сосед по азимуту» — это
та же самая точка, и любой признак непрерывности выродится в тождество.

## Почему признак считается по ОБРАТНОЙ дальности

Напрашивающееся «разница дальности с соседом ниже порога» не работает в тоннеле
принципиально. Стена идёт почти вдоль луча, и на 40 м соседние азимуты лежат на
ней с разбегом дальности больше метра: для плоскости на расстоянии w по нормали
dr/dθ ≈ r²/w, то есть при w = 2.5 м и r = 40 м один шаг 0.1° даёт 1.7 м. Любой
порог в метрах на таком признаке объявит всю дальнюю стену разрывом.

Но у плоскости есть точное свойство: 1/r ЛИНЕЙНА по направляющим косинусам.
Вдоль кольца 1/r = A·cosθ + B·sinθ + C, и на шаге 0.1° вторая разность такого
выражения меньше (1/r)·(dθ)² ≈ 10⁻⁶ — то есть ноль. Поэтому признаком служит
ВТОРАЯ РАЗНОСТЬ ОБРАТНОЙ ДАЛЬНОСТИ, а не первая разность дальности: она равна
нулю на плоскости при любом угле падения, включая скользящий.

Чтобы порог задавался в метрах, вторая разность домножается на r²:

    step = |Δ²(1/r)| · r²   — метры

Это и есть «скачок дальности, из которого вычтен наклон поверхности». Множитель
r² — не подгонка, а якобиан перехода: разрыв в δ метров на дальности r меняет
1/r ровно на δ/r². Порог получается константой в метрах, а его зависимость от
дальности берётся из геометрии, а не из подбора на одном прогоне.
"""

import numpy as np

N_RINGS = 128
MIN_RANGE = 0.1        # м: ближе этого — «нет возврата», а не точка
SURFACE_STEP = 0.15    # м: больший деприцированный скачок — это край, а не поверхность


def unfold(points):
    """Облако -> сетка (азимут × кольцо) без дубликатов колонок.

    Возвращает dict с полями формы (n_az, 128) и `index` — индексами исходных
    точек, чтобы любую посчитанную по сетке метку можно было вернуть точкам.
    None, если раскладка не совпала (чужой сенсор, битый кадр).
    """
    n = len(points)
    if n % N_RINGS:
        return None
    n_col = n // N_RINGS
    idx = np.arange(n).reshape(n_col, N_RINGS)
    x = points['x'].astype(np.float32).reshape(n_col, N_RINGS)
    y = points['y'].astype(np.float32).reshape(n_col, N_RINGS)
    z = points['z'].astype(np.float32).reshape(n_col, N_RINGS)
    if n_col % 2 == 0 and _columns_are_paired(x, y, z):
        idx, x, y, z = idx[0::2], x[0::2], y[0::2], z[0::2]
    rng = np.sqrt(x * x + y * y + z * z)
    return {"index": idx, "x": x, "y": y, "z": z, "range": rng, "valid": rng > MIN_RANGE}


def _columns_are_paired(x, y, z, sample=200, tol=1e-3):
    """Проверка дублирования соседних колонок — по выборке, а не по всей сетке:
    ответ бинарный и одинаковый по всему кадру, гонять по 300 тысячам точек
    ради него незачем."""
    a = slice(0, 2 * sample, 2)
    b = slice(1, 2 * sample, 2)
    same = (np.abs(x[a] - x[b]) < tol) & (np.abs(y[a] - y[b]) < tol) & (np.abs(z[a] - z[b]) < tol)
    return float(same.mean()) > 0.9


def ring_elevation(grid):
    """Угол места каждого кольца, радианы — из самого кадра, а не из паспорта
    сенсора. У OT128 кольца расставлены НЕРАВНОМЕРНО (в середине обзора гуще),
    поэтому шаг между соседними кольцами знать обязательно: без него вторая
    разность по кольцам меряет не кривизну поверхности, а неравномерность
    сетки. Медиана по валидным точкам кольца — оценка устойчивая и дешёвая."""
    v = grid["valid"]
    r = np.maximum(grid["range"], MIN_RANGE)
    el = np.where(v, np.arcsin(np.clip(grid["z"] / r, -1, 1)), np.nan)
    with np.errstate(all="ignore"):
        out = np.nanmedian(el, axis=0)
    return np.where(np.isfinite(out), out, 0.0)


def surface_step(grid, axis=0, coords=None):
    """Деприцированный скачок дальности вдоль оси, метры.

    Считается как отклонение 1/r у точки от линейной интерполяции между
    соседями, умноженное на r²:

        step = |1/r₁ − ((1−w)/r₀ + w/r₂)| · r₁²,   w = h₁/(h₁+h₂)

    Ноль на любой плоскости независимо от угла падения (см. docstring модуля).
    Линейная интерполяция, а не симметричная вторая разность, потому что шаг
    между соседями бывает неравномерным (кольца OT128); при равномерном шаге
    выражение вырождается в обычную половину второй разности.

    coords: положения узлов вдоль оси (углы). None = шаг равномерный.

    Там, где хоть один из трёх соседей невалиден, возвращается inf: у точки на
    границе видимости соседа нет, и «поверхность» о ней утверждать нельзя. Это
    не пропуск, а часть ответа — край тени объекта тоже не поверхность.
    """
    r = grid["range"]
    v = grid["valid"]
    inv = np.where(v, 1.0 / np.maximum(r, MIN_RANGE), 0.0)
    prev, nxt = np.roll(inv, 1, axis=axis), np.roll(inv, -1, axis=axis)
    vp, vn = np.roll(v, 1, axis=axis), np.roll(v, -1, axis=axis)

    if coords is None:
        w = 0.5
    else:
        c = np.asarray(coords, dtype=float)
        h1 = c - np.roll(c, 1)
        h2 = np.roll(c, -1) - c
        with np.errstate(divide="ignore", invalid="ignore"):
            w = np.where(np.abs(h1 + h2) > 1e-12, h1 / (h1 + h2), 0.5)
        w = np.clip(np.nan_to_num(w, nan=0.5), 0.05, 0.95)
        w = w.reshape([-1 if i == axis else 1 for i in range(v.ndim)])

    out = np.abs(inv - ((1.0 - w) * prev + w * nxt)) * r * r
    # Края сетки заворачиваются roll'ом на противоположный край — там соседства нет
    edge = np.zeros_like(v)
    for pos in (0, -1):
        sl = [slice(None)] * v.ndim
        sl[axis] = pos
        edge[tuple(sl)] = True
    return np.where(~(v & vp & vn) | edge, np.inf, out)


def surface_mask(points, step_tol=SURFACE_STEP, both_axes=False, keep_isolated=False):
    """Маска «точка лежит на сплошной поверхности» в порядке ИСХОДНЫХ точек.

    both_axes: требовать гладкости и по азимуту, и по кольцам. По умолчанию
        ВЫКЛЮЧЕНО, и это результат замера, а не экономия. Шаг по азимуту
        равномерный и мелкий (0.1°), поэтому скачок по нему у стены — 7 мм.
        Кольца стоят в 10 раз реже, а деприцированный скачок растёт как квадрат
        шага, поэтому у той же стены по кольцам получается уже ~0.9 м: в полосе
        высот 0.9 м соседние кольца регулярно попадают одно на стену, другое на
        пол или свод. Признак по кольцам меряет не гладкость стены, а грубость
        сетки, и разделяет он вчетверо хуже (AUC 0.27 против 0.24 при
        несопоставимо большем разбросе).

    None, если кадр не раскладывается в сетку — вызывающий код должен тогда
    работать по полному облаку, а не падать.
    """
    n_grid = (len(points) // N_RINGS) * N_RINGS
    grid = unfold(points[:n_grid])
    if grid is None:
        return None

    def pass_(step):
        return (step < step_tol) | (np.isinf(step) if keep_isolated else False)

    ok = pass_(surface_step(grid, axis=0))
    if both_axes:
        ok &= pass_(surface_step(grid, axis=1, coords=ring_elevation(grid)))
    mask = np.zeros(len(points), dtype=bool)
    mask[grid["index"].ravel()] = ok.ravel()
    # Хвост, не укладывающийся в сетку, — это точки, подклеенные накоплением из
    # прошлых кадров (rail_detection.accumulate). Сетки у них уже нет, но отбор
    # по непрерывности они прошли тогда, когда были своим кадром.
    mask[n_grid:] = True
    return mask
