"""Накопление нескольких кадров в одно облако со сдвигом на пройденный путь.

Задача, ради которой всё: на 50–80 м точек в клиренс-полосе не хватает на
локализацию границы, и дальность наблюдения упирается в ~45 м (§17), тогда как
по ТЗ она оценивается от 100 м. Кадр приходит каждые 0.1 с, поезд проезжает за
это время около полутора метров — десять кадров подряд смотрят почти на один и
тот же кусок тоннеля с десяти близких позиций. Сложив их, получаем то же облако
вдесятеро плотнее там, где плотности и не хватало.

## Почему складывать надо в координатах ПУТИ, а не сенсора

Напрашивающееся «сдвинуть прошлый кадр на Δs по оси глубины» на повороте даёт
грубую ошибку. Точка на глубине p в текущем кадре в прошлом кадре была на
глубине p + Δs, и её боковое положение там измерялось от ДРУГОЙ касательной:
для дуги радиуса R разница составляет ((p+Δs)² − p²)/2R ≈ p·Δs/R. При p = 40 м,
накопленном сдвиге 7 м и R = 300 м это 0.9 м — больше самой полуширины
тоннеля. Никакого накопления после такого не выйдет, точки размажет поперёк.

В координатах пути (d, u, v) этой ошибки нет по построению: u и v привязаны к
самому пути, а не к положению поезда, поэтому при движении вперёд у точки
меняется РОВНО d, на Δs. Остаточная ошибка — это ошибка оценки самого пути,
а она измерена и составляет около 4 см (§16, ось на отложенных рельсах).

## Что именно накапливается

Только клиренс-полоса, и это сознательное ограничение. Полоса — то, по чему
ищется боковая граница, и именно ей не хватает плотности вдали. Пол и рельсы
остаются от ТЕКУЩЕГО кадра нетронутыми: детектор рельсов работает вблизи, где
плотности и так достаточно, а накопление с ошибкой в Δs размазало бы головку
рельса и увело бы опору. Меньше риска и ровно та же польза.

## Чего это стоит и чем опасно

Движущиеся объекты накопление размазывает — это неустранимое свойство метода,
а не дефект реализации. Поэтому накопленное облако годится для ГЕОМЕТРИИ
тоннеля, но не для поиска препятствий: препятствие надо искать в текущем кадре,
сравнивая его с геометрией, снятой по накопленному. Проверка на
`doubleT_obstacle` показывает, во что именно превращается стоящий поезд.

Ошибка в Δs накапливается линейно, поэтому окно короткое и постоянно
пересвязывается: хвост старше N кадров выбрасывается целиком, а не хранится.
"""

from collections import deque

import numpy as np

from .loader import POINT_DTYPE
from .shift import MAX_SHIFT, estimate_shift
from .tunnel_frame import V_HI, V_LO, to_track_coords

N_FRAMES = 5          # кадров в окне накопления (текущий плюс прошлые)
D_MIN, D_MAX = 3.0, 100.0   # глубины, в которых накопленная точка ещё осмысленна
# Ближе этой глубины прошлые точки в слитое облако не идут. По умолчанию порога
# НЕТ, и это результат замера, опровергшего правдоподобное рассуждение. Довод был
# такой: вблизи плотности и так на порядки больше нужного, а каждая подклеенная
# точка несёт ошибку оценки пути своего кадра и разбавляет ею самую надёжную
# часть подгонки; значит накопление должно заниматься только дальней зоной.
# Замер (dev, N=5) сказал обратное — ближние точки помогают, а не мешают:
#
#   порог      обе стены   ось, медиана   дальность
#   нет          99.4%        0.049 м       78.5 м
#   15 м         98.5%        0.049 м       77.1 м
#   25 м         98.9%        0.045 м       75.8 м
#   35 м         98.7%        0.044 м       78.5 м
#
# Ось от отсечки чуть выигрывает, стены — заметно проигрывают, и выигрыш оси
# вчетверо меньше проигрыша стен. Объяснение: согласование срезов идёт по всему
# кадру сразу, и лишние ближние срезы не «разбавляют», а удерживают полуширину
# на участках, где дальняя часть кадра неоднозначна.
D_ACC_MIN = 0.0
MAX_DRIFT = 0.30      # м: накопленная неопределённость Δs, дальше окно обрывается
SHIFT_SIGMA = 0.03    # м: оценка ошибки одного измерения Δs (расхождение способов)


def track_band(points, frame, v_lo=V_LO, v_hi=V_HI, d_max=D_MAX):
    """Клиренс-полоса кадра в координатах пути плюс всё, что нужно, чтобы потом
    вернуть точки в координаты сенсора."""
    x = points['x'].astype(float)
    y = points['y'].astype(float)
    z = points['z'].astype(float)
    d, u, v = to_track_coords(x, y, z, frame)
    band = (v >= v_lo) & (v <= v_hi) & (d > D_MIN) & (d < d_max)
    return {"d": d[band], "u": u[band], "v": v[band],
            "intensity": points['intensity'][band], "ring": points['ring'][band],
            "timestamp": points['timestamp'][band]}


def to_sensor_points(band, frame):
    """Обратный переход (d, u, v) -> точки в координатах сенсора текущего кадра.

    Обращение to_track_coords один в один: глубина — это −y, боковое смещение
    делится на cos(курс) (в координатах пути оно по нормали, в координатах
    сенсора — по срезу), высота отсчитывается от профиля пола.
    """
    from .curvature import eval_fit, slope_from_fit
    d = band["d"]
    xc = eval_fit(frame["axis_fit"], d)
    heading = np.arctan(slope_from_fit(frame["axis_fit"], d))
    out = np.zeros(len(d), dtype=POINT_DTYPE)
    out['x'] = xc + band["u"] / np.cos(heading)
    out['y'] = -d
    out['z'] = band["v"] + np.polyval(frame["floor_coeffs"], d)
    out['intensity'] = band["intensity"]
    out['ring'] = band["ring"]
    out['timestamp'] = band["timestamp"]
    return out


class FrameAccumulator:
    """Скользящее окно кадров, сложенных со сдвигом на пройденный путь.

    Применяется последовательным проходом по записи; reset() при переходе к
    другой записи — соседние записи ничем не связаны.
    """

    def __init__(self, n_frames=N_FRAMES, max_drift=MAX_DRIFT, d_max=D_MAX,
                 d_min=D_ACC_MIN):
        self.n_frames = int(n_frames)
        self.max_drift = max_drift
        self.d_max = d_max
        self.d_min = d_min
        self.reset()

    def reset(self):
        # maxlen ровно n_frames − 1: окно в N кадров — это текущий плюс N−1
        # прошлых. При n_frames = 1 очередь нулевой длины, и накопления нет
        # вовсе; это рабочий режим (контрольный замер «как было»), а не вырождение.
        self.hist = deque(maxlen=max(0, self.n_frames - 1))
        self.prev_band = None
        self.last = {}

    def push(self, points, frame, steps=1):
        """Принимает кадр вместе с его опорой и возвращает СЛИТОЕ облако.

        frame — опора текущего кадра (`res["frame"]`), уже посчитанная по одному
        этому кадру. Без неё координаты пути не построить, а без них складывать
        кадры нельзя (см. docstring модуля).
        """
        band = track_band(points, frame, d_max=self.d_max)
        est = {"shift": float("nan"), "contrast": 0.0, "ok": False}
        if self.prev_band is not None:
            est = estimate_shift(self.prev_band, band, max_shift=_max_shift(steps))
        self.prev_band = band
        shift = est["shift"]

        if not est["ok"]:
            # Смещение не измерено — накапливать не на что. Честнее отдать один
            # кадр, чем сложить его с прошлым по выдуманному сдвигу.
            self.hist.clear()
            if self.hist.maxlen:
                self.hist.append({"band": band, "drift": 0.0})
            self.last = {**est, "n_merged": 1}
            return points

        merged = [points]
        kept = deque(maxlen=self.hist.maxlen)
        for rec in self.hist:
            d = rec["band"]["d"] - shift
            drift = rec["drift"] + SHIFT_SIGMA
            if drift > self.max_drift:
                continue
            sel = (d >= D_MIN) & (d < self.d_max)
            if sel.sum() < 50:
                continue
            moved = {k: v[sel] for k, v in rec["band"].items()}
            moved["d"] = d[sel]
            # В историю запись кладётся целиком (на следующем шаге её ближняя
            # часть уедет ещё дальше назад и выпадет сама), а в слитое облако —
            # только дальняя: см. D_ACC_MIN.
            kept.append({"band": moved, "drift": drift})
            out = moved["d"] >= self.d_min
            if out.sum() >= 50:
                merged.append(to_sensor_points({k: v[out] for k, v in moved.items()}, frame))
        kept.append({"band": band, "drift": 0.0})
        self.hist = kept
        self.last = {**est, "n_merged": len(merged)}
        return np.concatenate(merged) if len(merged) > 1 else points


def _max_shift(steps):
    """Предел перебора сдвига растёт с шагом прохода: при шаге 4 между кадрами
    выборки проходит 0.4 с, и поезд успевает проехать вчетверо больше."""
    return MAX_SHIFT * max(1, int(steps))
