"""Поиск того, что ДВИЖЕТСЯ относительно тоннеля.

## Зачем это отдельно от габарита

Габаритный коридор (`gauge.py`) отвечает на вопрос «что мешает проехать». Он
ничего не знает про то, опасен ли предмет, и по построению пропускает всё, что
рядом с путём, но не на нём. На `doubleT_obstacle` это и случилось: двое людей
идут по служебному проходу на `u ≈ +2.0…2.25 м`, то есть в 0.7–0.9 м от края
габарита, и статическая проверка их не видит — она и не должна.

Расширить коридор нельзя: замер на зоне `|u| < 2.0 м` даёт кластеры в 95–100%
кадров ВСЕХ прогонов, включая чистые. Рядом с путём стоит инфраструктура —
контактный рельс, лотки, знаки, — и отличить её от человека по одному положению
невозможно.

Зато отличить можно по ДВИЖЕНИЮ: тоннель неподвижен, человек нет.

## Почему это стало возможно только сейчас

§11 попробовал ровно это — сравнение соседних кадров — и получил отрицательный
результат: 58–99% кадров с крупным «аномальным» кластером. Причина была
установлена там же и точно: эгомоушн. Один и тот же луч в двух кадрах смотрит на
разные точки тоннеля, потому что поезд проехал вперёд, и разница кадров
показывает движение поезда, а не движение в кадре. Вывод §11 звучал так:
«требует предварительной компенсации движения... отдельная нетривиальная
подзадача».

§20 эту подзадачу решил: продольное смещение Δs меряется по облаку двумя
независимыми способами и сходится до сантиметра. Компенсация теперь есть, и
метод §11 можно доставать обратно — но уже с вычтенным движением.

## Как устроено

Прошлый кадр берётся в координатах пути, его глубины сдвигаются на измеренное Δs
и раскладываются по сетке. Занятые сейчас ячейки, которых не было в сдвинутом
прошлом, — это изменение. Кластеры изменений и есть кандидаты.

Сетка 15 см: мельче — и разрешение самого лидара на 30 м даст «изменение» на
каждой стене, крупнее — и человек перестанет отличаться от шума.

Ограничение честное и существенное: **объект, неподвижный относительно тоннеля,
этим способом не виден**. Стоящий поезд, упавший предмет, забытый инструмент —
для них нужен габаритный коридор, и два детектора дополняют друг друга ровно
там, где каждый слеп. Плюс на стоянке (Δs = 0) вырождается подтверждение по
движению в `gauge.ObstacleWatch`, а этот детектор, наоборот, работает лучше
всего — сдвигать нечего, и разница кадров чистая.
"""

import numpy as np

VOXEL = 0.15          # м: сетка сравнения
EPS = 0.45            # м: радиус DBSCAN по изменившимся ячейкам
MIN_SAMPLES = 6
MIN_VOXELS = 15       # ячеек в кластере: меньше — мерцание разрежённых дальних точек
HEIGHT_MIN = 0.8      # м: ниже — не человек и не предмет в габарите, а рябь пути
FOOTPRINT_MAX = 3.0   # м: шире — это кусок стены, а не отдельный предмет
D_MIN, D_MAX = 1.5, 70.0


def _voxels(d, u, v, d_min=D_MIN, d_max=D_MAX, size=VOXEL):
    sel = (d > d_min) & (d < d_max) & (np.abs(u) < 8.0) & (v > -0.5) & (v < 4.5)
    if sel.sum() == 0:
        return np.zeros((0, 3), dtype=np.int64)
    k = np.floor(np.column_stack([d[sel], u[sel], v[sel]]) / size).astype(np.int64)
    return np.unique(k, axis=0)


class MotionDetector:
    """Последовательный проход по кадрам одной записи.

    Состояние — занятость прошлого кадра в координатах пути. Сбрасывается при
    переходе к другой записи и при потере Δs: без измеренного смещения
    компенсировать нечего, и сравнивать кадры бессмысленно (это и есть случай
    §11).
    """

    def __init__(self, voxel=VOXEL):
        self.voxel = voxel
        self.reset()

    def reset(self):
        self.prev = None

    def update(self, d, u, v, shift):
        """Принимает координаты пути текущего кадра и измеренное Δs.
        Возвращает список кластеров изменений."""
        cur = _voxels(d, u, v, size=self.voxel)
        prev = self.prev
        self.prev = cur
        if prev is None or shift is None or not np.isfinite(shift):
            return []

        # Прошлый кадр сдвигается вперёд на пройденный путь: то, что было на
        # глубине D, теперь на D − Δs. Сдвиг целочисленный по сетке — доля
        # ячейки тут не важна, а округление одинаково для всех ячеек и потому
        # не создаёт ложных изменений само по себе.
        moved = prev.copy()
        moved[:, 0] -= int(round(shift / self.voxel))

        old = set(map(tuple, moved))
        new = np.array([k for k in map(tuple, cur) if k not in old], dtype=float)
        if len(new) < MIN_SAMPLES:
            return []
        return _cluster(new * self.voxel)


def _cluster(pts):
    from sklearn.cluster import DBSCAN

    labels = DBSCAN(eps=EPS, min_samples=MIN_SAMPLES).fit_predict(pts)
    out = []
    for lab in np.unique(labels[labels >= 0]):
        m = labels == lab
        if m.sum() < MIN_VOXELS:
            continue
        c = pts[m]
        size = c.max(axis=0) - c.min(axis=0)
        # Отбор по форме: у человека или предмета есть высота и ограниченный
        # след. Кусок стены, «поехавший» из-за неточности Δs, высокий, но
        # длинный — его отсекает FOOTPRINT_MAX по глубине.
        if size[2] < HEIGHT_MIN or size[0] > FOOTPRINT_MAX or size[1] > FOOTPRINT_MAX:
            continue
        out.append({"depth": float(c[:, 0].min()), "n": int(m.sum()),
                    "u": float(np.median(c[:, 1])), "v_top": float(c[:, 2].max()),
                    "size": tuple(float(t) for t in size)})
    out.sort(key=lambda c: c["depth"])
    return out
