"""Продольное смещение Δs между кадрами — единственная ненаблюдаемая величина.

Зачем это вообще. Прошлый кадр до сих пор использовался так, будто поезд стоял:
медиана кривизны, прошлые полуширины, маска стен — ни в одном из них нет
поправки на то, что сцена уехала назад. А точки прошлых кадров не использовались
вовсе, и каждый кадр видел только свои 307 200 точек. Чтобы сложить кадры в одно
облако, нужно и достаточно знать Δs.

Почему не ICP. Тоннель — хрестоматийный вырожденный случай лидарной одометрии:
через два метра он выглядит так же, матрица сопоставления вырождается, и полный
ICP уходит в дрейф по той самой оси, которая нам нужна. Но полная одометрия нам
и не требуется: боковое смещение и рыскание стены ограничивают прекрасно, и мы
их уже оцениваем. Ненаблюдаемая компонента ровно одна — продольная, и здесь
оценивается именно она, ОДНИМ параметром.

Два независимых способа, и замер расставил их не так, как ожидалось:

  по плотности — число точек клиренс-полосы по глубине как одномерный сигнал;
      тренд 1/r² снимается делением на скользящее среднее, и остаётся ровно
      продольная текстура. ОСНОВНОЙ способ: контраст пика на реальных кадрах
      доходит до 80, то есть максимум один и он резкий.

  по занятости — облако кладётся в трёхмерную решётку координат пути (u, v, d) и
      сдвигается по глубине; берётся сдвиг с наибольшим перекрытием занятых
      ячеек. ПРОВЕРОЧНЫЙ: сходится с первым до сантиметра там, где работает, но
      у него есть системный дефект (ниже). Держится ради независимости: два
      способа, устроенные по-разному, ошибаются по-разному.

Предполагалось обратное — что прямая корреляция профиля надёжнее, а периодичность
обделки её испортит. Периодичность не помешала: у неё период порядка метра, а
текстура кадра содержит и непериодические детали (ниши, кронштейны, стыки), и
корреляция по 540 бинам разрешает их однозначно.

## Системный дефект меры по занятости: самоподобие на нулевом сдвиге

Тоннель продольно однороден, поэтому облако почти совпадает само с собой при
ЛЮБОМ сдвиге, и перекрытие занятости состоит из большой «фоновой» части, которая
от сдвига почти не зависит, плюс маленькой части от реальной текстуры. Фон при
нулевом сдвиге чуть выше (те же ячейки той же гладкой стены), и на кадрах с
бедной текстурой он перевешивает настоящий пик: на разобранной паре 79→80
`roundT_pressureGate_roundT` счёт при нуле 0.719 против 0.707 у верного пика
1.5 м. Получается ровно нулевое смещение при явно движущемся поезде — 5–10% пар.

Снять фон вычитанием гладкого тренда из самой кривой счёта пробовали: не
помогает, потому что фон не описывается низкой степенью, а настоящий пик узкий
(±0.1 м) и в тренд не уходит. Поэтому мера по занятости оставлена как есть и
используется только для сверки, а решение принимается по плотности.

Обе меры сообщают не только сдвиг, но и КОНТРАСТ пика — отношение пика к лучшему
значению за его пределами. Контраст около единицы означает, что продольной
структуры в этом куске тоннеля нет и смещение здесь не измеримо; тогда честнее
признать «не знаю», чем выдать положение максимума шума.
"""

import numpy as np

MAX_SHIFT = 3.0        # м: больше поезд метро за 0.1 с не проезжает (22 м/с = 79 км/ч)
STEP = 0.05            # м: разрешение перебора сдвига
U_BIN, V_BIN = 0.20, 0.20   # м: решётка занятости поперёк пути
D_BIN = 0.10           # м: и вдоль него
MIN_CONTRAST = 1.5     # ниже — продольной структуры нет, сдвиг не измерим
DENSITY_SMOOTH = 25    # бинов: ширина окна, которым снимается тренд 1/r²


def estimate_shift(prev, cur, max_shift=MAX_SHIFT, min_contrast=MIN_CONTRAST,
                   cross_check=False):
    """Продольное смещение между кадрами: сколько метров поезд проехал вперёд.

    prev/cur — словари с массивами d, u, v (клиренс-полоса кадра в координатах
    пути). Решение принимается по профилю плотности; мера по занятости считается
    только если запрошена сверка, потому что она в двадцать раз дороже.

    Возвращает dict: shift (NaN, если не измерено), contrast, ok, и при
    cross_check — shift_occupancy и их расхождение.
    """
    shift, contrast = estimate_shift_density(prev, cur, max_shift=max_shift)
    out = {"shift": shift, "contrast": contrast,
           "ok": bool(np.isfinite(shift) and contrast >= min_contrast)}
    if cross_check:
        s_occ, q_occ = estimate_shift_occupancy(prev, cur, max_shift=max_shift)
        out["shift_occupancy"] = s_occ
        out["occupancy_contrast"] = q_occ
        out["disagreement"] = abs(s_occ - shift) if np.isfinite(s_occ + shift) else float("nan")
    return out


def frame_time(points):
    """Момент кадра по пер-точечным таймстампам — медиана, а не первый и не
    последний. Внутри кадра таймстампы размазаны на 32 мс: сенсор сканирует
    сектор ±50° за это время, и края развёртки относятся к разным моментам.
    Разность медиан по двум кадрам даёт Δt точно (на всех шести записях ровно
    0.1000 с), а не по номинальным 10 Гц из заголовка."""
    return float(np.median(points['timestamp'].astype(float)))


def _peak(score, lo, step):
    """Положение максимума с субпиксельным уточнением по параболе и контраст.

    Контраст — отношение пика к лучшему значению ВНЕ его окрестности. Он
    отвечает на единственный важный вопрос: этот максимум один или таких же
    несколько. У периодической обделки их несколько, и тогда доверять положению
    максимума нельзя, каким бы высоким он ни был.
    """
    k = int(np.argmax(score))
    best = float(score[k])
    if best <= 0:
        return float("nan"), 0.0
    guard = max(1, int(round(0.5 / step)))     # ±0.5 м вокруг пика — та же деталь
    outside = np.concatenate([score[:max(0, k - guard)], score[k + guard + 1:]])
    contrast = best / max(float(outside.max()), 1e-9) if len(outside) else np.inf

    shift = lo + k * step
    if 0 < k < len(score) - 1:
        a, b, c = score[k - 1], score[k], score[k + 1]
        den = a - 2 * b + c
        if den < 0:
            shift += step * 0.5 * (a - c) / den
    return float(shift), float(contrast)


def estimate_shift_occupancy(prev, cur, max_shift=MAX_SHIFT, d_max=60.0):
    """Δs по перекрытию занятых ячеек решётки (u, v, d) координат пути.

    prev/cur — словари с массивами d, u, v (клиренс-полоса кадра).

    Сравнение идёт только в полосе глубин, которая есть в ОБОИХ кадрах при любом
    пробуемом сдвиге: иначе выигрывает сдвиг, при котором просто больше ячеек
    попало в пересечение, и оценка систематически уезжает к нулю.
    """
    d_lo = float(max(prev["d"].min(), cur["d"].min())) + max_shift
    if d_lo + 5.0 >= d_max:
        return float("nan"), 0.0
    nu = int(np.ceil(14.0 / U_BIN))
    nv = max(1, int(np.ceil((prev["v"].max() - prev["v"].min() + 1e-6) / V_BIN)))
    nd = int(np.ceil((d_max - d_lo) / D_BIN))
    if nd < 20:
        return float("nan"), 0.0

    def grid(f, shift):
        """Занятость (u, v, d) после сдвига кадра вперёд на shift метров."""
        d = f["d"] - shift
        sel = (d >= d_lo) & (d < d_max)
        if sel.sum() < 200:
            return None
        iu = np.clip(((f["u"][sel] + 7.0) / U_BIN).astype(np.int64), 0, nu - 1)
        iv = np.clip(((f["v"][sel] - prev["v"].min()) / V_BIN).astype(np.int64), 0, nv - 1)
        id_ = ((d[sel] - d_lo) / D_BIN).astype(np.int64)
        flat = (iu * nv + iv) * nd + id_
        out = np.zeros(nu * nv * nd, dtype=bool)
        out[flat] = True
        return out.reshape(nu * nv, nd)

    ref = grid(cur, 0.0)
    if ref is None:
        return float("nan"), 0.0
    n_ref = float(np.count_nonzero(ref))
    if n_ref <= 0:
        return float("nan"), 0.0

    n_steps = int(round(max_shift / STEP)) + 1
    score = np.zeros(n_steps)
    # Сдвиг перебирается по ЦЕЛЫМ ячейкам решётки (D_BIN кратен STEP только в
    # среднем), поэтому prev бинуется заново на каждом шаге: округление сдвига к
    # решётке дало бы ступеньку в 10 см там, где нужна точность в сантиметры.
    #
    # Мера — ДОЛЯ совпавших ячеек (Дайс), а не их число. Это не косметика:
    # чем больше сдвиг, тем меньше точек прошлого кадра вообще остаётся в общей
    # полосе глубин (дальний край кадра разрежён), поэтому абсолютное число
    # совпадений падает с ростом сдвига само по себе, и максимум систематически
    # уезжает к нулю. Первая версия именно так и вела себя: на трети кадров
    # выдавала ровно нулевое смещение при явно движущемся поезде.
    for i in range(n_steps):
        g = grid(prev, i * STEP)
        if g is None:
            continue
        n_g = float(np.count_nonzero(g))
        if n_g > 0:
            score[i] = 2.0 * float(np.count_nonzero(g & ref)) / (n_g + n_ref)
    return _peak(score, 0.0, STEP)


def estimate_shift_density(prev, cur, max_shift=MAX_SHIFT, d_max=60.0):
    """Δs по одномерному профилю плотности точек вдоль глубины.

    Тренд 1/r² снимается делением на скользящую медиану: он одинаков в обоих
    кадрах, сдвига в себе не несёт и, будучи на порядок больше самой текстуры,
    задавил бы её в корреляции.
    """
    d_lo = float(max(prev["d"].min(), cur["d"].min())) + max_shift
    edges = np.arange(d_lo, d_max + D_BIN, D_BIN)
    if len(edges) < 40:
        return float("nan"), 0.0

    def profile(d):
        h = np.histogram(d, bins=edges)[0].astype(float)
        base = np.convolve(h, np.ones(DENSITY_SMOOTH) / DENSITY_SMOOTH, mode="same")
        return h / np.maximum(base, 1.0) - 1.0

    a = profile(prev["d"])
    b = profile(cur["d"])
    n_steps = int(round(max_shift / D_BIN)) + 1
    score = np.zeros(n_steps)
    for i in range(n_steps):
        # prev сдвинут вперёд на i бинов — значит сравнивается его хвост с
        # началом cur той же длины
        aa, bb = a[i:], b[:len(b) - i]
        n = min(len(aa), len(bb))
        if n < 30:
            continue
        aa, bb = aa[:n], bb[:n]
        sa, sb = aa.std(), bb.std()
        score[i] = float(np.dot(aa - aa.mean(), bb - bb.mean()) / (n * sa * sb)) if sa * sb > 0 else 0.0
    score = np.maximum(score, 0.0)
    return _peak(score, 0.0, D_BIN)
